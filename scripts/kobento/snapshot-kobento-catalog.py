#!/usr/bin/env python3
"""Snapshot Kobento's component library and generate a UI Builder catalog from it.

Kobento's components live in its private MCP server, so the only machine-readable listing is the
server's own `find {"kind": "components", "interface": true}` answer. This script turns that answer
into two committed files:

  kobento-components-snapshot-v1.json   the interface facts only (names, params, slots, sets)
  kobento-published-v1.json             a `ui-builder.json` that serves every component as a builtin

Usage:

  snapshot-kobento-catalog.py fetch     # needs a Kobento token (see below); rewrites both files
  snapshot-kobento-catalog.py generate  # snapshot -> published file, offline
  snapshot-kobento-catalog.py check     # fails if the published file is not what `generate` writes

A token comes from https://mcp.kobento.dev/ (free account). Locally, put it in KOBENTO_TOKEN; in a
cloud session whose proxy injects the credential, leave KOBENTO_TOKEN unset.

See docs/design/UI_BUILDER_KOBENTO.md for why the snapshot keeps only interface facts and why the
catalog is all builtins.
"""

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "docs" / "design" / "fixtures" / "ui-builder"
SNAPSHOT = FIXTURES / "kobento-components-snapshot-v1.json"
PUBLISHED = FIXTURES / "kobento-published-v1.json"
ENDPOINT = "https://mcp.kobento.dev/mcp"

PREFIX = "kobento/"

# Kobento param type -> the jsonType a design value is checked against. `action` params are not
# properties: a design states clicks as eventBindings, which the exporter writes as `onClick`.
JSON_TYPES = {
    "float": "number",
    "string": "string",
    "text": "string",
    # Kobento reads a bool as true/false or an exact 0/1, so either kind of state binds.
    "bool": ["boolean", "number"],
    "color": "string",
    "enum": "string",
    "list": "array",
    # A variable the component reads and writes itself (Switch.checked): a 0/1 or a number.
    "variable": ["boolean", "number"],
}

LOOKS = ["light", "dark", "mono-dark", "mono-light"]


def kebab(name: str) -> str:
    """`ActivityRings` -> `activity-rings`, `Chart3D` -> `chart3-d`; inverted by [pascal]."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name).lower()


def pascal(component_id: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in component_id.split("-"))


def display_name(name: str) -> str:
    return re.sub(r"(?<=[a-z])(?=[A-Z0-9])", " ", name)


def fetch() -> dict:
    body = json.dumps(
        {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "tools/call",
            "params": {
                "name": "find",
                "arguments": {"kind": "components", "interface": True, "limit": 1000},
            },
        }
    ).encode()
    headers = {
        "content-type": "application/json",
        "accept": "application/json, text/event-stream",
    }
    token = os.environ.get("KOBENTO_TOKEN")
    if token:
        headers["authorization"] = f"Bearer {token}"
    request = urllib.request.Request(ENDPOINT, data=body, headers=headers, method="POST")
    with urllib.request.urlopen(request, timeout=120) as response:
        answer = json.loads(response.read())
    if "error" in answer:
        sys.exit(f"Kobento answered an error: {answer['error']}")
    return json.loads(answer["result"]["content"][0]["text"])


def snapshot_of(found: dict) -> dict:
    """Interface facts only: no summaries or docs, which are Kobento's prose, not a contract."""
    components = []
    for component in sorted(found["components"], key=lambda c: c["name"]):
        name = component["name"]
        if pascal(kebab(name)) != name:
            sys.exit(f"{name}: does not survive the id round trip ({kebab(name)})")
        params = {}
        for param, spec in component.get("params", {}).items():
            params[param] = {
                key: spec[key]
                for key in ("type", "required", "default", "static", "values")
                if key in spec
            }
        slots = {slot: {"optional": spec.get("optional", True)}
                 for slot, spec in component.get("slots", {}).items()}
        components.append({"name": name, "params": params, "slots": slots})
    if len(components) != found.get("total", len(components)):
        sys.exit(f"find answered {len(components)} of {found.get('total')} components")
    return {
        "$comment": (
            "GENERATED by scripts/kobento/snapshot-kobento-catalog.py fetch from Kobento's MCP "
            "`find {kind: components, interface: true}`. Interface facts only. Regenerate, do "
            "not edit; see docs/design/UI_BUILDER_KOBENTO.md."
        ),
        "source": ENDPOINT,
        "sets": [s["name"] for s in found.get("sets", [])],
        "components": components,
    }


def notes(spec: dict) -> str:
    parts = [f"Kobento type {spec['type']}"]
    if "default" in spec:
        parts.append(f"default {json.dumps(spec['default'])}")
    if spec.get("static"):
        parts.append("static: fixed when the call is expanded, not bindable to state")
    elif spec["type"] in ("float", "bool", "color", "string"):
        parts.append('a literal or a "@variable"')
    return "; ".join(parts)


def property_of(name: str, spec: dict) -> dict:
    prop = {"name": name, "jsonType": JSON_TYPES[spec["type"]]}
    if spec.get("required"):
        prop["required"] = True
    if spec.get("values"):
        prop["allowedValues"] = spec["values"]
    prop["notes"] = notes(spec)
    return prop


def published_of(snapshot: dict) -> dict:
    builtins = {
        # The document itself: Kobento's root column on the theme background.
        PREFIX + "document": {
            "role": "screen-root",
            "displayName": "Kobento document",
            "canvas": "placeholder",
            "slots": {"content": {"ordered": True}},
        },
        # The format's own text primitive, not a library component.
        PREFIX + "text": {
            "role": "element",
            "displayName": "Text",
            "canvas": "placeholder",
            "properties": [
                {"name": "value", "jsonType": "string", "required": True,
                 "notes": 'the text, or a "@variable"'},
                {"name": "fontSize", "jsonType": "number", "notes": "sp"},
                {"name": "color", "jsonType": "string",
                 "notes": '"#AARRGGBB" or a theme token such as "@colors.onSurface"'},
            ],
        },
    }
    menu = {PREFIX + "text": {"group": "Text"}}
    for component in snapshot["components"]:
        name = component["name"]
        component_id = PREFIX + kebab(name)
        params = component["params"]
        builtin = {
            "role": "element",
            "displayName": display_name(name),
            "canvas": "placeholder",
            "properties": [
                property_of(param, spec)
                for param, spec in params.items()
                if spec["type"] != "action"
            ],
        }
        if component["slots"]:
            builtin["slots"] = {
                slot: {"required": not spec["optional"], "ordered": True}
                for slot, spec in component["slots"].items()
            }
        builtins[component_id] = builtin
        menu[component_id] = {"group": "Components"}
    clickable = sorted(
        PREFIX + kebab(c["name"])
        for c in snapshot["components"]
        if c["params"].get("onClick", {}).get("type") == "action"
    )
    return {
        "$comment": (
            "GENERATED by scripts/kobento/snapshot-kobento-catalog.py generate from "
            "kobento-components-snapshot-v1.json. Every component is a builtin: Kobento components "
            "have no Kotlin call site, so there is no record. See docs/design/UI_BUILDER_KOBENTO.md."
        ),
        "schema": "compose-ui-builder-catalog/v1",
        "catalog": {
            "id": "kobento",
            "title": "Kobento components",
            "platform": "remote-compose",
            "platformLabel": "Kobento",
        },
        "statusSemantics": {
            "platform": "remote-compose",
            "platformLabel": "Kobento",
            "componentIdPrefix": PREFIX,
            "previewSurfaces": {
                "wasm": {
                    "fidelity": "approximate",
                    "reason": (
                        "Kobento components are expanded by Kobento's server, not composed. The "
                        "canvas draws each as a labelled placeholder; the picture comes from "
                        "playing the converted .rc."
                    ),
                },
            },
            "frame": {"adapter": "frame/rect"},
            "componentMenu": {"groupOrder": ["Text", "Components"], "components": menu},
            "builtins": builtins,
            # Read by the Kobento exporter, passed through verbatim by every other reader.
            "kobento": {
                "componentSets": snapshot["sets"],
                "looks": LOOKS,
                "clickable": clickable,
                # Params fixed when a call is expanded: the exporter refuses state bound to them.
                "staticParams": {
                    PREFIX + kebab(c["name"]): sorted(
                        p for p, spec in c["params"].items() if spec.get("static")
                    )
                    for c in snapshot["components"]
                    if any(spec.get("static") for spec in c["params"].values())
                },
            },
        },
    }


def write(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def main() -> None:
    command = sys.argv[1] if len(sys.argv) > 1 else "check"
    if command == "fetch":
        write(SNAPSHOT, snapshot_of(fetch()))
        command = "generate"
    snapshot = json.loads(SNAPSHOT.read_text())
    if command == "generate":
        write(PUBLISHED, published_of(snapshot))
    elif command == "check":
        expected = json.dumps(published_of(snapshot), indent=2, ensure_ascii=False) + "\n"
        if PUBLISHED.read_text() != expected:
            sys.exit(f"{PUBLISHED.relative_to(ROOT)} is stale: run {Path(__file__).name} generate")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
